export enum OperationType {
  CREATE = 'create',
  UPDATE = 'update',
  DELETE = 'delete',
  LIST = 'list',
  GET = 'get',
  WRITE = 'write',
}

interface FirestoreErrorInfo {
  error: string;
  operationType: OperationType;
  path: string | null;
  authInfo: {
    userId?: string | null;
    email?: string | null;
    emailVerified?: boolean | null;
    isAnonymous?: boolean | null;
    tenantId?: string | null;
    providerInfo?: {
      providerId?: string | null;
      email?: string | null;
    }[];
  };
}

interface FirebaseRuntimeConfig {
  apiKey: string;
  authDomain: string;
  projectId: string;
  storageBucket: string;
  messagingSenderId: string;
  appId: string;
  firestoreDatabaseId?: string;
}

// Optional runtime config generated by platform provisioning when env vars are not manually provided
const provisionedConfigs = import.meta.glob('../../firebase-applet-config.json', {
  eager: true,
}) as Record<string, { default?: Partial<FirebaseRuntimeConfig> }>;

function resolveFirebaseConfig(): FirebaseRuntimeConfig | null {
  const envApiKey = import.meta.env.VITE_FIREBASE_API_KEY?.trim() || '';
  const envAuthDomain = import.meta.env.VITE_FIREBASE_AUTH_DOMAIN?.trim() || '';
  const envProjectId = import.meta.env.VITE_FIREBASE_PROJECT_ID?.trim() || '';
  const envStorageBucket = import.meta.env.VITE_FIREBASE_STORAGE_BUCKET?.trim() || '';
  const envMessagingSenderId = import.meta.env.VITE_FIREBASE_MESSAGING_SENDER_ID?.trim() || '';
  const envAppId = import.meta.env.VITE_FIREBASE_APP_ID?.trim() || '';
  const envDatabaseId = import.meta.env.VITE_FIREBASE_DATABASE_ID?.trim() || undefined;

  if (envApiKey && envAuthDomain && envProjectId && envAppId) {
    return {
      apiKey: envApiKey,
      authDomain: envAuthDomain,
      projectId: envProjectId,
      storageBucket: envStorageBucket,
      messagingSenderId: envMessagingSenderId,
      appId: envAppId,
      firestoreDatabaseId: envDatabaseId,
    };
  }

  const provisioned = Object.values(provisionedConfigs)[0]?.default;
  if (
    provisioned?.apiKey &&
    provisioned?.authDomain &&
    provisioned?.projectId &&
    provisioned?.appId &&
    provisioned.projectId !== 'remixed-project-id'
  ) {
    return {
      apiKey: provisioned.apiKey,
      authDomain: provisioned.authDomain,
      projectId: provisioned.projectId,
      storageBucket: provisioned.storageBucket || '',
      messagingSenderId: provisioned.messagingSenderId || '',
      appId: provisioned.appId,
      firestoreDatabaseId: provisioned.firestoreDatabaseId || undefined,
    };
  }

  return null;
}

const runtimeConfig = resolveFirebaseConfig();

export const isFirebaseConfigured = Boolean(runtimeConfig);

let app: FirebaseApp | null = null;
let auth: Auth | null = null;
let db: Firestore | null = null;

if (runtimeConfig) {
  app = getApps().length > 0 ? getApps()[0] : initializeApp(runtimeConfig);
  auth = getAuth(app);
  try {
    db = initializeFirestore(
      app,
      {
        experimentalForceLongPolling: true,
      },
      runtimeConfig.firestoreDatabaseId
    );
  } catch {
    db = runtimeConfig.firestoreDatabaseId
      ? getFirestore(app, runtimeConfig.firestoreDatabaseId)
      : getFirestore(app);
  }
}

export { auth, db };

export function handleFirestoreError(
  error: unknown,
  operationType: OperationType,
  path: string | null
): never {
  const errInfo: FirestoreErrorInfo = {
    error: error instanceof Error ? error.message : String(error),
    authInfo: {
      userId: auth?.currentUser?.uid,
      email: auth?.currentUser?.email,
      emailVerified: auth?.currentUser?.emailVerified,
      isAnonymous: auth?.currentUser?.isAnonymous,
      tenantId: auth?.currentUser?.tenantId,
      providerInfo:
        auth?.currentUser?.providerData?.map((provider) => ({
          providerId: provider.providerId,
          email: provider.email,
        })) || [],
    },
    operationType,
    path,
  };
  console.error('Firestore Error: ', JSON.stringify(errInfo));
  throw new Error(JSON.stringify(errInfo));
}

async function testConnection(): Promise<void> {
  if (!db) return;
  try {
    await getDocFromServer(doc(db, 'test', 'connection'));
  } catch (error) {
    if (error instanceof Error && error.message.includes('the client is offline')) {
      console.error('Please check your Firebase configuration.');
    }
  }
}

if (db && typeof window !== 'undefined') {
  void testConnection();
}

async function ensureLocalPersistence(): Promise<Auth> {
  if (!auth) {
    throw new Error('Cloud sync is not configured.');
  }
  await setPersistence(auth, browserLocalPersistence);
  return auth;
}

export async function signInWithEmail(email: string, password: string): Promise<User> {
  const authInstance = await ensureLocalPersistence();
  const cred = await signInWithEmailAndPassword(authInstance, email.trim(), password);
  return cred.user;
}

export async function registerWithEmail(
  fullName: string,
  email: string,
  password: string
): Promise<User> {
  const authInstance = await ensureLocalPersistence();
  const trimmedName = fullName.trim();
  const cred = await createUserWithEmailAndPassword(authInstance, email.trim(), password);
  if (trimmedName) {
    await updateProfile(cred.user, { displayName: trimmedName });
  }
  return cred.user;
}

export async function signInWithGoogle(): Promise<User> {
  const authInstance = await ensureLocalPersistence();
  const provider = new GoogleAuthProvider();
  provider.setCustomParameters({ prompt: 'select_account' });
  const cred = await signInWithPopup(authInstance, provider);
  return cred.user;
}

export async function signOutUser(): Promise<void> {
  if (!auth) return;
  await signOut(auth);
}

export function subscribeAuthState(callback: (user: User | null) => void): Unsubscribe {
  if (!auth) {
    callback(null);
    return () => {};
  }
  return onAuthStateChanged(auth, callback);
}

function getWellnessDocPath(uid: string): string {
  return `users/${uid}/wellness/state`;
}

export async function pushUserWellnessState(
  uid: string,
  email: string,
  state: AppState,
  includeCreatedAt = false
): Promise<void> {
  if (!db) return;
  const path = getWellnessDocPath(uid);
  const docRef = doc(db, 'users', uid, 'wellness', 'state');
  const payload = serializeToFirestorePayload(uid, email, state);

  try {
    if (includeCreatedAt) {
      await setDoc(
        docRef,
        {
          ...payload,
          createdAt: serverTimestamp(),
          updatedAt: serverTimestamp(),
        },
        { merge: true }
      );
    } else {
      await setDoc(
        docRef,
        {
          ...payload,
          updatedAt: serverTimestamp(),
        },
        { merge: true }
      );
    }
  } catch (error) {
    handleFirestoreError(error, includeCreatedAt ? OperationType.CREATE : OperationType.UPDATE, path);
  }
}

export async function mergeAndSyncOnLogin(
  user: User,
  localState: AppState
): Promise<{ mergedState: AppState; existedInCloud: boolean }> {
  if (!db) {
    return { mergedState: localState, existedInCloud: false };
  }
  const path = getWellnessDocPath(user.uid);
  const docRef = doc(db, 'users', user.uid, 'wellness', 'state');
  const todayKey = formatDateKey(new Date());

  let cloudState: AppState | null = null;
  let existedInCloud = false;

  try {
    const snap = await getDoc(docRef);
    if (snap.exists()) {
      existedInCloud = true;
      cloudState = deserializeFromFirestorePayload(snap.data(), todayKey);
    }
  } catch (error) {
    const msg = error instanceof Error ? error.message : '';
    if (!msg.includes('client is offline')) {
      handleFirestoreError(error, OperationType.GET, path);
    }
  }

  const displayName = user.displayName || localState.profile.name || 'Student';
  const mergedState = mergeLocalAndCloudState(localState, cloudState, displayName);

  await pushUserWellnessState(user.uid, user.email || '', mergedState, !existedInCloud);
  return { mergedState, existedInCloud: true };
}

export function subscribeUserWellnessState(
  uid: string,
  onRemoteState: (state: AppState) => void,
  onSyncError?: (error: Error) => void
): Unsubscribe {
  if (!db) return () => {};
  const path = getWellnessDocPath(uid);
  const docRef = doc(db, 'users', uid, 'wellness', 'state');

  return onSnapshot(
    docRef,
    (snapshot) => {
      if (!snapshot.exists() || snapshot.metadata.hasPendingWrites) {
        return;
      }
      const hydrated = deserializeFromFirestorePayload(snapshot.data(), formatDateKey(new Date()));
      if (hydrated) {
        onRemoteState(hydrated);
      }
    },
    (error) => {
      try {
        handleFirestoreError(error, OperationType.GET, path);
      } catch (wrapped) {
        if (onSyncError && wrapped instanceof Error) {
          onSyncError(wrapped);
        }
      }
    }
  );
}
